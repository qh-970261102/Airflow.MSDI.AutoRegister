        Assert.DoesNotContain("AddTwo(IServiceCollection services)", code, "不应为多余的 [AutoRegister] 方法生成实现");
        Assert.AreEqual(1, CountOccurrences(code, "services.AddKeyedSingleton<global::Demo.ServiceA>(__key1);"), "注册体应只生成一份");
    }

