namespace Airflow.MSDI.AutoRegister.Test;

/// <summary>验证生成代码的结构(不运行容器)。</summary>
[TestClass]
public sealed class GeneratorSnapshotTests
{
    private const string Source = """
        using System;
        using Microsoft.Extensions.DependencyInjection;

        namespace Demo;

        [SingletonService]
        public class ServiceA { }

        [ScopedService]
        public class ServiceB { }

        [TransientService]
        public class ServiceC { }

        [SingletonService(typeof(InterfaceD))]
        public class ServiceD : InterfaceD { }

        [SingletonService]
        [SingletonService(typeof(InterfaceE))]
        public class ServiceE : InterfaceE { }

        [SingletonService(typeof(InterfaceF), 2)]
        public class ServiceF : InterfaceF { }

        [SingletonService(typeof(InterfaceF), 1)]
        public class ServiceG : InterfaceF { }

        public class ServiceH
        {
            [SingletonService]
            public ServiceI GetServiceI() => new();
            [ScopedService]
            public ServiceJ GetServiceJ(IServiceProvider sp) => new();
        }

        public interface InterfaceD { }
        public interface InterfaceE { }
        public interface InterfaceF { }
        public class ServiceI { }
        public class ServiceJ { }

        internal static partial class Register
        {
            [AutoRegister]
            public static partial void AddServicesFromCurrentAssembly(IServiceCollection services);

            public static IServiceCollection AddServices(this IServiceCollection services)
            {
                AddServicesFromCurrentAssembly(services);
                return services;
            }
        }
        """;

    [TestMethod]
    public void Generates_PartialMethodImplementation()
    {
        var (code, _, _) = GeneratorTestHelper.RunGenerator(Source);

        StringAssert.Contains(code, "public static partial void AddServicesFromCurrentAssembly(IServiceCollection services)");
        StringAssert.Contains(code, "internal static partial class Register");
        StringAssert.Contains(code, "// <auto-generated/>");
    }

    [TestMethod]
    public void Generates_AnchorAndAlias_EvenForSingleRegistration()
    {
        var (code, _, _) = GeneratorTestHelper.RunGenerator("""
            using Microsoft.Extensions.DependencyInjection;
            namespace Demo;
            [SingletonService]
            public class ServiceA { }
            internal static partial class Register
            {
                [AutoRegister]
                public static partial void AddServices(IServiceCollection services);
            }
            """);

        // 单条注册也统一走 object 锚点:锚点 + 别名
        Assert.AreEqual("__key1", AnchorKey(code, "global::Demo.ServiceA"));
        StringAssert.Contains(code, "services.AddKeyedSingleton<global::Demo.ServiceA>(__key1);");
        StringAssert.Contains(code, "services.AddSingleton<global::Demo.ServiceA>(sp => sp.GetRequiredKeyedService<global::Demo.ServiceA>(__key1));");
    }

    [TestMethod]
    public void Generates_BasicLifetimeRegistrations()
    {
        var (code, _, _) = GeneratorTestHelper.RunGenerator(Source);

        foreach (var (impl, keyedMethod, plainMethod) in new[]
                 {
                     ("ServiceA", "AddKeyedSingleton", "AddSingleton"),
                     ("ServiceB", "AddKeyedScoped", "AddScoped"),
                     ("ServiceC", "AddKeyedTransient", "AddTransient"),
                 })
        {
            var display = "global::Demo." + impl;
            var anchor = AnchorKey(code, display);
            StringAssert.Contains(code, $"services.{keyedMethod}<{display}>({anchor});");
            StringAssert.Contains(code, $"services.{plainMethod}<{display}>(sp => sp.GetRequiredKeyedService<{display}>({anchor}));");
        }
    }

