namespace Airflow.MSDI.AutoRegister.Test;

/// <summary>验证生成代码的结构(不运行容器)。</summary>
[TestClass]
public sealed class GeneratorSnapshotTests
{
    private const string Source = """
        using System;
        using Microsoft.Extensions.DependencyInjection;

        namespace Demo;

        [SingletonService]
        public class ServiceA { }

        [ScopedService]
        public class ServiceB { }

        [TransientService]
        public class ServiceC { }

        [SingletonService(typeof(InterfaceD))]
        public class ServiceD : InterfaceD { }

        [SingletonService]
        [SingletonService(typeof(InterfaceE))]
        public class ServiceE : InterfaceE { }

        [SingletonService(typeof(InterfaceF), 2)]
        public class ServiceF : InterfaceF { }

        [SingletonService(typeof(InterfaceF), 1)]
        public class ServiceG : InterfaceF { }

        public class ServiceH
        {
            [SingletonService]
            public ServiceI GetServiceI() => new();
            [ScopedService]
            public ServiceJ GetServiceJ(IServiceProvider sp) => new();
        }

        public interface InterfaceD { }
        public interface InterfaceE { }
        public interface InterfaceF { }
        public class ServiceI { }
        public class ServiceJ { }

        internal static partial class Register
        {
            [AutoRegister]
            public static partial void AddServicesFromCurrentAssembly(IServiceCollection services);

            public static IServiceCollection AddServices(this IServiceCollection services)
            {
                AddServicesFromCurrentAssembly(services);
                return services;
            }
        }
        """;

    [TestMethod]
    public void Generates_PartialMethodImplementation()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator(Source);

        StringAssert.Contains(code, "public static partial void AddServicesFromCurrentAssembly(IServiceCollection services)");
        StringAssert.Contains(code, "internal static partial class Register");
        StringAssert.Contains(code, "// <auto-generated/>");
    }

    [TestMethod]
    public void Generates_BasicLifetimeRegistrations()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator(Source);

        StringAssert.Contains(code, "services.AddSingleton<global::Demo.ServiceA>();");
        StringAssert.Contains(code, "services.AddScoped<global::Demo.ServiceB>();");
        StringAssert.Contains(code, "services.AddTransient<global::Demo.ServiceC>();");
    }

    [TestMethod]
    public void Generates_InterfaceDirectRegistration_WhenNoSelfRegistration()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator(Source);

        // ServiceD 只有接口注册 → AddSingleton<InterfaceD, ServiceD>()
        StringAssert.Contains(code, "services.AddSingleton<global::Demo.InterfaceD, global::Demo.ServiceD>();");
    }

    [TestMethod]
    public void Generates_InterfaceViaSelf_WhenSelfRegistrationExists()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator(Source);

        // ServiceE 有自身注册 → 接口注册指向同一单例
        StringAssert.Contains(code, "services.AddSingleton<global::Demo.ServiceE>();");
        StringAssert.Contains(code, "services.AddSingleton<global::Demo.InterfaceE>(sp => sp.GetRequiredService<global::Demo.ServiceE>());");
    }

    [TestMethod]
    public void Orders_ByOrder_ThenByTypeName()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator(Source);

        // ServiceG order=1 先于 ServiceF order=2
        var gIndex = code.IndexOf("global::Demo.InterfaceF, global::Demo.ServiceG>();", StringComparison.Ordinal);
        var fIndex = code.IndexOf("global::Demo.InterfaceF, global::Demo.ServiceF>();", StringComparison.Ordinal);
        Assert.IsTrue(gIndex >= 0 && fIndex > gIndex, "ServiceG(order=1) 应在 ServiceF(order=2) 之前注册");
    }

    [TestMethod]
    public void Generates_FactoryMethodRegistrations_WithOwnerSingletonOnce()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator(Source);

        // 拥有类只注册一次单例
        var ownerCount = CountOccurrences(code, "services.AddSingleton<global::Demo.ServiceH>();");
        Assert.AreEqual(1, ownerCount, "ServiceH 应只注册一次单例");

        StringAssert.Contains(code, "services.AddSingleton<global::Demo.ServiceI>(sp => sp.GetRequiredService<global::Demo.ServiceH>().GetServiceI());");
        StringAssert.Contains(code, "services.AddScoped<global::Demo.ServiceJ>(sp => sp.GetRequiredService<global::Demo.ServiceH>().GetServiceJ(sp));");
    }

    [TestMethod]
    public void NoAutoRegisterMethod_GeneratesNothing()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator("""
            namespace Demo;
            [SingletonService]
            public class ServiceA { }
            """);

        Assert.AreEqual(string.Empty, code);
    }

    [TestMethod]
    public void MultipleAutoRegisterMethods_EachGeneratesOwnImplementation()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator("""
            using Microsoft.Extensions.DependencyInjection;
            namespace Demo;
            [SingletonService]
            public class ServiceA { }

            internal static partial class Register
            {
                [AutoRegister]
                public static partial void AddOne(IServiceCollection services);
                [AutoRegister]
                public static partial void AddTwo(IServiceCollection services);
            }
            """);

        StringAssert.Contains(code, "AddOne(IServiceCollection services)");
        StringAssert.Contains(code, "AddTwo(IServiceCollection services)");
        var count = CountOccurrences(code, "services.AddSingleton<global::Demo.ServiceA>();");
        Assert.AreEqual(2, count, "每个 [AutoRegister] 方法都应包含完整注册体");
    }

    [TestMethod]
    public void CustomAttribute_WithRegistrationOptions_IsSupported()
    {
        var (code, _) = GeneratorTestHelper.RunGenerator("""
            using System;
            using Microsoft.Extensions.DependencyInjection;
            namespace Demo;

            [RegistrationOptions(
                LifetimeIndex = -1,
                ServiceTypeIndex = 0,
                OrderIndex = 1,
                DefaultLifetime = ServiceLifetime.Transient,
                DefaultServiceType = null,
                DefaultOrder = 0)]
            public sealed class CustomServiceAttribute : BaseServiceAttribute
            {
                public CustomServiceAttribute(Type? serviceType = null, double order = 0)
                    : base(ServiceLifetime.Transient, serviceType, order) { }
            }

            [CustomService(typeof(InterfaceX))]
            public class ServiceX : InterfaceX { }

            public interface InterfaceX { }

            internal static partial class Register
            {
                [AutoRegister]
                public static partial void AddServices(IServiceCollection services);
            }
            """);

        StringAssert.Contains(code, "services.AddTransient<global::Demo.InterfaceX, global::Demo.ServiceX>();");
    }

    private static int CountOccurrences(string haystack, string needle)
    {
        int count = 0, index = 0;
        while ((index = haystack.IndexOf(needle, index, StringComparison.Ordinal)) >= 0)
        {
            count++;
            index += needle.Length;
        }
        return count;
    }
}
