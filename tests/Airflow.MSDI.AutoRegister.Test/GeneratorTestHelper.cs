using System.Collections.Immutable;
using System.Reflection;
using System.Runtime.Loader;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Airflow.MSDI.AutoRegister.Generator;

namespace Airflow.MSDI.AutoRegister.Test;

/// <summary>运行源生成器的测试辅助。</summary>
internal static class GeneratorTestHelper
{
    public static readonly MetadataReference[] References = BuildReferences();

    private static MetadataReference[] BuildReferences()
    {
        var refs = new List<MetadataReference>();
        var tpa = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Where(p => !string.IsNullOrWhiteSpace(p));
        foreach (var path in tpa)
        {
            refs.Add(MetadataReference.CreateFromFile(path));
        }

        // 生成器所在程序集(包含属性类型)。
        refs.Add(MetadataReference.CreateFromFile(typeof(BaseServiceAttribute).Assembly.Location));

        return refs.ToArray();
    }

    /// <summary>用给定源码跑生成器,返回(生成的源代码, 输出编译, 生成器诊断)。</summary>
    public static (string GeneratedCode, Compilation OutputCompilation, ImmutableArray<Diagnostic> GeneratorDiagnostics) RunGenerator(string source)
    {
        var tree = CSharpSyntaxTree.ParseText(source);
        var compilation = CSharpCompilation.Create(
            "GeneratorTestAssembly",
            new[] { tree },
            References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));

        var driver = CSharpGeneratorDriver.Create(new AutoRegisterGenerator());
        driver.RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out var diagnostics);

        var generated = outputCompilation.SyntaxTrees
            .Where(t => t.FilePath.Contains(".g.cs") || t.ToString().Contains("<auto-generated/>"))
            .Select(t => t.ToString())
            .ToList();

        return (string.Join("\n\n", generated), outputCompilation, diagnostics);
    }

    /// <summary>把编译产物加载到独立 ALC,返回程序集。</summary>
    public static Assembly LoadAssembly(Compilation compilation)
    {
        using var ms = new MemoryStream();
        var result = compilation.Emit(ms);
        if (!result.Success)
        {
            var errors = string.Join("\n", result.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));
            throw new InvalidOperationException($"编译失败:\n{errors}");
        }

        ms.Position = 0;
        var alc = new AssemblyLoadContext("generator-test-" + Guid.NewGuid().ToString("N"), isCollectible: true);
        alc.Resolving += (_, name) =>
        {
            try { return Assembly.Load(name.Name!); }
            catch { return null; }
        };
        return alc.LoadFromStream(ms);
    }
}
